#!/usr/bin/env python3
"""Normalise the generated catalogue into assets/products.js.

Products arrive as {"en":[13 items], "zh":[13 items]} from the copy pass. This script joins
them by id, attaches the SVG path, and emits one structure the renderer can use for either
language plus the shop filters.

Run: python3 build_products.py
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / ".build" / "products.json"
OUT = HERE / "assets" / "products.js"

LINE_META = {
    "Spring": {"slug": "spring", "zh": "涌泉"},
    "Feast": {"slug": "feast", "zh": "盛宴"},
    "Still": {"slug": "still", "zh": "静谧"},
    "Play": {"slug": "play", "zh": "嬉戏"},
    "Care": {"slug": "care", "zh": "养护"},
}

CATEGORY_ORDER = ["Fountains", "Feeders", "Bowls", "Play", "Care"]


def main():
    if not SRC.exists():
        sys.exit("products.json missing")
    data = json.loads(SRC.read_text(encoding="utf-8"))
    en, zh = data.get("en", []), data.get("zh", [])
    zh_by_id = {p["id"]: p for p in zh}

    items, problems = [], []
    for p in en:
        pid = p["id"]
        z = zh_by_id.get(pid)
        if not z:
            problems.append(f"no zh copy for {pid}")
            z = p
        img = f"assets/products/{pid}.svg"
        if not (HERE / img).exists():
            problems.append(f"missing art {img}")
        item = {
            "id": pid,
            "img": img,
            "price": p.get("price", 0),
            "compareAt": p.get("compareAt", 0),
            "line": p.get("line", ""),
            "lineSlug": LINE_META.get(p.get("line", ""), {}).get("slug", "all"),
            "category": p.get("category", ""),
            "badge": p.get("badge", ""),
            "colors": [{"hex": c.get("hex", "#cccccc")} for c in p.get("colors", [])],
            "en": {
                "name": p.get("name", pid),
                "tagline": p.get("tagline", ""),
                "desc": p.get("desc", ""),
                "bullets": p.get("bullets", []),
                "specs": p.get("specs", []),
                "colorNames": [c.get("name", "") for c in p.get("colors", [])],
            },
            "zh": {
                "name": z.get("name", pid),
                "tagline": z.get("tagline", ""),
                "desc": z.get("desc", ""),
                "bullets": z.get("bullets", []),
                "specs": z.get("specs", []),
                "colorNames": [c.get("name", "") for c in z.get("colors", [])],
            },
        }
        items.append(item)

    order = {c: i for i, c in enumerate(CATEGORY_ORDER)}
    items.sort(key=lambda x: (order.get(x["category"], 99), -x["price"]))

    js = "/* Generated by build_products.py — edit .build/products.json, not this file. */\n"
    js += "window.PRODUCTS = " + json.dumps(
        {"items": items, "lines": LINE_META, "order": [i["id"] for i in items]},
        ensure_ascii=False, indent=1) + ";\n"
    OUT.write_text(js, encoding="utf-8")

    print(f"wrote {OUT.relative_to(HERE)} — {len(items)} products")
    for w in problems:
        print("  !", w)
    if len(items) != 13:
        print(f"  ! expected 13 products, got {len(items)}")


if __name__ == "__main__":
    main()
